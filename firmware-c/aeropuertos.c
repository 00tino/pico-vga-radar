const aeropuerto_dato_t *aeropuerto_buscar(const char *iata) {
    int lo = 0, hi = AEROPUERTOS_CANT - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        int cmp = strncmp(iata, aeropuertos[m].iata, 3);
        if (cmp == 0) return &aeropuertos[m];
        if (cmp < 0) hi = m - 1; else lo = m + 1;
    }
    return 0;
}
